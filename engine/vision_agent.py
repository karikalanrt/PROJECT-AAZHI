                    if not line:
                        continue

                    try:
                        chunk = json.loads(line.decode("utf-8"))
                    except (json.JSONDecodeError, UnicodeDecodeError):
                        continue

                    # Detect Ollama engine-level error payloads e.g. {"error": "model output error..."}
                    if "error" in chunk:
                        err_msg = chunk["error"]
                        yield f"\n\n⚠️ **Ollama model error:** `{err_msg}`\n\n"
