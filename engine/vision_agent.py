    @staticmethod
    def encode_image_to_base64(image_input, max_dim: int = 896) -> str:
        """
        Encodes a filepath, PIL Image, or bytes to a base64 string for Ollama.
        Smartly resizes massive rasters to optimal visual token resolution (<= 896px)
        to prevent GPU VRAM overflow, avoid context-length overflow, and accelerate inference.
        896px is chosen because qwen2.5vl:3b has a 896x896 native visual token grid.
        """
        if isinstance(image_input, str):
            pil_img = Image.open(image_input)
        elif isinstance(image_input, Image.Image):
            pil_img = image_input
        elif isinstance(image_input, bytes):
            pil_img = Image.open(io.BytesIO(image_input))
        else:
            raise TypeError("Unsupported image type for base64 encoding.")

        if pil_img.mode != "RGB":
            pil_img = pil_img.convert("RGB")

        # Smart downscale if either dimension exceeds max_dim
        w, h = pil_img.size
        if max(w, h) > max_dim:
            scale = max_dim / float(max(w, h))
            new_size = (int(w * scale), int(h * scale))
            pil_img = pil_img.resize(new_size, Image.Resampling.BILINEAR)

        buffer = io.BytesIO()
        pil_img.save(buffer, format="JPEG", quality=85)
        return base64.b64encode(buffer.getvalue()).decode("utf-8")

